"""The no-repaint theorem for order blocks, breakers, mitigation blocks and OTEs (G2 §3).

`test_no_repaint_zones.py` covers the zones built from candle geometry alone,
and `test_no_repaint_replays.py` the structure replays. That left §5.1-§5.3 and
§5.8's zones, the ones built on top of *other engines' evidence*: an order
block's grade reads the structure break its displacement made, a breaker and a
mitigation block read the break at their parent's invalidation, and §5.3's
failure swing reads two external pivots. Each of those is a place where a
replay could use a fact that did not exist yet when the zone was decided.

Each example runs the real S4 -> S5 -> S6 pipeline (`engine: "ict_evidence"`
in the golden harness) once on a prefix and once on the whole series. Every
OB, breaker, mitigation block and OTE the prefix created must exist on the
whole series with the same type, polarity, grade, band, birth and parent, and
every transition the prefix recorded for one must be recorded there too.
Later candles may add zones and transitions; that is the market moving on.

**What this found (s6-ob-v8), and why v9 exists.** The order-block replay
picked its structure evidence by the pivot's own time, but §3.1 writes a
pivot's record five candles after it prints (v1.0.9, internal and external
alike). A whole-window run therefore read records a live pass deciding that
OB never had. Two shapes, both caught here: on 120 generated series one order
block was OB_A on the prefix and OB_B on the whole series (a higher pivot two
candles before the displacement, not yet recorded), and under a first draft
of the fix that used k = 2 for internal records, an OB_B on a 328-candle
prefix that the 349-candle run never created. v9 reads evidence as recorded
by the deciding candle, and stops deciding a displacement on the newest one.

**Aimed splits.** The defect needs a prefix that ends between a displacement's
decision and the confirmation of a pivot printed just before it -- a window of
about four candles. A uniform split lands there rarely (1 in 120 above), so
half the examples end the prefix two to six candles after a displacement.
"""

from __future__ import annotations

import asyncio
import json
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

import pytest
from hypothesis import HealthCheck, event, given, settings
from hypothesis import strategies as st
from tests.golden.harness import runner
from tests.golden.harness.canonical import canonicalise
from tests.golden.harness.dataset import GoldenDataset
from tests.support.strategies import walking_candle_series

from scanner.domain.common import wilder_atr_series
from scanner.domain.ict import detect_displacement

pytestmark = pytest.mark.property

_WARM = 300
_MAX_SERIES = 380

# The zones whose formation reads another engine's evidence (§5.1-§5.3) plus
# §5.8's OTE, which reads the dealing range. FVG, IFVG and BPR are geometry
# only and are covered in test_no_repaint_zones.py.
_TYPES = frozenset({"OB", "BREAKER", "MITIGATION", "OTE"})

_REPLAY_SETTINGS = settings(
    max_examples=25,
    deadline=None,
    suppress_health_check=[HealthCheck.too_slow, HealthCheck.data_too_large],
)


def _dataset(candles: list) -> GoldenDataset:
    return GoldenDataset(
        dataset_id="property-ict-evidence",
        engine="ict_evidence",
        sls_sections=("5.1",),
        sls_rules=("property",),
        description="generated",
        labelling_rationale="generated by a property test",
        labelled_by="hypothesis",
        labelled_at="generated",
        algo_version="property",
        symbol=candles[0].symbol,
        timeframe=candles[0].timeframe,
        candles=tuple(candles),
        expected={},
        path=Path("generated.json"),
    )


def _run(candles: list) -> dict[str, Any]:
    result: dict[str, Any] = canonicalise(
        asyncio.run(runner._run_ict(_dataset(candles), with_evidence=True))
    )

    return result


def _zones(result: dict[str, Any]) -> dict[tuple[str, ...], list[tuple[Any, ...]]]:
    """Zone facts grouped by what places them in time.

    Grouped rather than keyed one-to-one: the harness aliases a zone as
    type:polarity:created_index, and two order blocks can share a birth candle
    with different bands. A one-to-one map silently compared the wrong pair --
    the first draft of this measurement reported 64 grade changes that were
    exactly that.
    """
    grouped: dict[tuple[str, ...], list[tuple[Any, ...]]] = defaultdict(list)

    for zone in result["zones"]:
        if zone["zone_type"] not in _TYPES:
            continue

        key = (zone["zone_type"], zone["polarity"], str(zone["created_index"]), zone["created_at"])
        fact = (zone["grade"], zone["band_low"], zone["band_high"], zone["parent_zone"])
        grouped[key].append(fact)

    return grouped


def _ends_after_a_displacement(series: list) -> list[int]:
    """Prefix lengths ending 2-6 candles after a displacement, inside the warm-up floor."""
    atrs = wilder_atr_series(series)
    ends: set[int] = set()

    for index in range(_WARM - 6, len(series)):
        atr = atrs[index]

        if atr is None or atr <= 0:
            continue

        if detect_displacement(series[: index + 1], index, atr=atr) is None:
            continue

        for after in range(2, 7):
            split = index + 1 + after

            if _WARM <= split < len(series):
                ends.add(split)

    return sorted(ends)


@_REPLAY_SETTINGS
@given(
    series=walking_candle_series(min_size=_WARM + 20, max_size=_MAX_SERIES),
    data=st.data(),
)
def test_an_evidence_built_zone_is_never_revoked_or_regraded(
    series: list,
    data: st.DataObject,
) -> None:
    """§5.1's grade is "evidence-derived and immutable", and so is everything after it."""

    aimed = _ends_after_a_displacement(series)

    if aimed and data.draw(st.booleans(), label="end the prefix just after a displacement"):
        event("prefix ends 2-6 candles after a displacement")
        split = data.draw(st.sampled_from(aimed), label="prefix")
    else:
        split = data.draw(st.integers(min_value=_WARM, max_value=len(series) - 1), label="prefix")

    early = _run(series[:split])
    later = _run(series)

    early_zones = _zones(early)
    later_zones = _zones(later)

    for key, facts in early_zones.items():
        event(f"prefix holds a {key[0]}")

        for fact in facts:
            assert fact in later_zones.get(key, []), (
                f"{key[0]} {key[1]} born at {key[3]} (index {key[2]}) on {split} candles as "
                f"(grade, low, high, parent) {fact} is not on the {len(series)}-candle run, "
                f"which has {later_zones.get(key, [])} there"
            )

    later_transitions = Counter(
        json.dumps(item, sort_keys=True)
        for item in later["transitions"]
        if item["zone_type"] in _TYPES
    )

    for item in early["transitions"]:
        if item["zone_type"] not in _TYPES:
            continue

        key = json.dumps(item, sort_keys=True)

        assert later_transitions[key] > 0, (
            f"{item['zone_type']} {item['from_state']} -> {item['to_state']} at candle "
            f"{item['candle_index']} on {split} candles was revoked or rewritten once the "
            f"series grew to {len(series)}"
        )

        later_transitions[key] -= 1
